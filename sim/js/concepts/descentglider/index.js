// two-pass full run: pass 1 finds the "ready" cue with the rider standing at the top; the rider pushes off at it
export function prepareFullRun(params, { caseId, seed, wind, plan, skier, post = POST_S } = {}) {
  const p = resolve(params);
  const c = caseId ? caseOf(caseId) : null;
  const w = wind || windOf(c);
  const base = simulateRun({ seed: seed ?? c.seed, ...(plan ? { plan } : {}), ...(skier ? { skier } : {}) });
  const sk0 = padRun(base, 30, 0);
  const c0 = runCore(p, { duration: DRAW_S + p.readyMax + 6, skier: sk0, wind: w, plan: { start: 'stowed', throwAt: DRAW_S } });
  if (c0.sum.interlock) { // wind interlock fired at the top: no follow this run — it lands near you, you pick it up first
    const skN = padRun(base, 60, 0);
    return { p, sk: skN, pre: null, noFly: true, input: { duration: DRAW_S + 40, skier: skN, wind: w, plan: { start: 'stowed', throwAt: DRAW_S } } };
  }
  const pre = Math.ceil(((c0.sum.tReady ?? DRAW_S + p.readyMax + 3) + 0.02) / 0.02) * 0.02;
  const sk = padRun(base, pre, post);
  const lastRide = sk.rides[sk.rides.length - 1];
  return { p, sk, pre, input: { duration: sk.duration - 0.04, skier: sk, wind: w, plan: { start: 'stowed', throwAt: DRAW_S, endAfter: lastRide.t0 + 3 } } };
}

function prepare(params, sc) {
  if (sc.kind === 'fullrun') {
    const pr = prepareFullRun(params, { caseId: sc.fr, plan: sc.plan, seed: sc.seed, wind: sc.wind });
    return { sk: pr.sk, input: pr.input, pre: pr.pre, dur: pr.input.duration, noFly: pr.noFly };
  }
  const sk = simulateSkier({ ...sc.skier });
  const plan = { ...(sc.plan || {}) };
  if (sc.trees) plan.trees = sc.trees.map(([x, y]) => ({ x, y, r: 2.2, h: 9 }));
  if (sc.neighbour) { const s = skierAt(sk, sc.neighbour.t0); plan.neighbour = { p0: [s.pos[0] + sc.neighbour.from[0], s.pos[1] + sc.neighbour.from[1], 0], v: sc.neighbour.v, t0: sc.neighbour.t0, t1: sc.neighbour.t1 }; }
  return { sk, input: { duration: sc.dur, skier: sk, wind: sc.wind, plan }, dur: sc.dur };
}

