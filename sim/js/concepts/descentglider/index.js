// per-run measurements shared by the Result, the ensemble runner and the tests
export function caseMetrics(core, A, sk, p, { pre = null, fullRun = false, noFly = false } = {}) {
  const O = core.O, n = core.n, dt = 0.02;
  const settle = core.plan.start === 'follow' ? 2 : 0;
  const skiing = new Uint8Array(n);
  let nSki = 0;
  for (let i = Math.round(settle / dt); i < n; i++) { const s = core.rider(i * dt); if (s.speed > 2 && !s.fallen) { skiing[i] = 1; nSki++; } }
  const good = (i) => A.cam[i] === 1 && A.inFrame[i] === 1 && A.px[i] >= 300;
  let nGood = 0, nLens = 0; const pxs = [];
  for (let i = 0; i < n; i++) if (skiing[i]) { if (good(i)) nGood++; if (A.cam[i] === 1 && A.lensOK[i] !== 1) nLens++; if (A.cam[i] === 1 && A.inFrame[i] === 1) pxs.push(A.px[i]); }
  const avail = nSki ? (100 * nGood) / nSki : NaN;
  // jitter: subject LOS vs the realised crop axis, >1 Hz
  const los = [], fwd = [], mask = new Uint8Array(n); let last = null;
  for (let i = 0; i < n; i++) {
    const ok = skiing[i] && A.cam[i] === 1 && A.lensOK[i] === 1 && Number.isFinite(A.lx[i]); // clamped (lost) frames are already counted unusable
    mask[i] = ok ? 1 : 0;
    if (ok) last = [[A.lx[i], A.ly[i], A.lz[i]], [A.fx[i], A.fy[i], A.fz[i]]];
    los.push(last ? last[0] : [1, 0, 0]); fwd.push(last ? last[1] : [1, 0, 0]);
  }
  const jh = jitterHP(los, fwd, dt, mask, 1);
  const jitter = Number.isFinite(jh.rms) ? Math.hypot(jh.rms, 0.3) : NaN; // ⊕ 0.3 °/s rolling-shutter/sync floor (ASSUMED)
  const vfovs = []; for (let i = 0; i < n; i++) if (mask[i] && Number.isFinite(A.vfov[i])) vfovs.push(A.vfov[i]);
  const jitterPct = (100 * jitter) / (med(vfovs) || CROP_VFOV);
  // gust-driven attitude disturbance (camera, before EIS)
  let dsq = 0, dn = 0; for (let i = 1; i < n; i++) if (mask[i]) { const r = [O.dph[i] - O.dph[i - 1], O.dth[i] - O.dth[i - 1], O.dps[i] - O.dps[i - 1]]; dsq += (r[0] ** 2 + r[1] ** 2 + r[2] ** 2) / (dt * dt); dn++; }
  const attRateRms = dn ? (Math.sqrt(dsq / dn) * 180) / Math.PI : NaN;
  const azLP = []; { let y = null; const k = 1 - Math.exp(-dt * 2 * Math.PI * 0.2); for (let i = 0; i < n; i++) { if (!skiing[i] || A.cam[i] !== 1 || !Number.isFinite(A.az[i])) continue; y = y == null ? A.az[i] : y + (A.az[i] - y) * k; azLP.push(y); } }
  const azRange = azLP.length > 50 ? pctl(azLP, 0.95) - pctl(azLP, 0.05) : NaN;
  let keMax = 0, headMin = Infinity, aglMin = Infinity, gsMax = 0;
  for (let i = 0; i < n; i++) {
    const md = O.mode[i];
    if (!isMoving(md)) continue;
    const ke = O.headD[i] > 1.5 ? A.keG[i] : A.keRel[i]; if (ke > keMax) keMax = ke;
    if (isFlying(md) && md !== MODE.THROWN) headMin = Math.min(headMin, O.headD[i]);
    if (md === MODE.FOLLOW || md === MODE.LOITER) aglMin = Math.min(aglMin, O.agl[i]);
    gsMax = Math.max(gsMax, Math.hypot(O.vx[i], O.vy[i], O.vz[i]));
  }
  const ev = core.events, has = (ty) => ev.some((e) => e.type === ty), evT = (ty) => { const e = ev.find((x) => x.type === ty); return e ? e.t : NaN; };
  // energy: from the throw (or t = 0) to rest (or the end)
  const tA = Number.isFinite(core.sum.tThrow) && core.sum.tThrow != null ? core.sum.tThrow : 0;
  const tB = core.sum.slide.restT ?? (n - 1) * dt;
  const iA = Math.round(tA / dt), iB = Math.min(n - 1, Math.round(tB / dt));
  const Ewh = O.E[iB] - O.E[iA], Trun = Math.max(1, tB - tA);
  const pMean = (Ewh * 3600) / Trun;
  const follow = []; for (let i = 0; i < n; i++) if (O.mode[i] === MODE.FOLLOW) follow.push(O.Pel[i]);
  const pFollow = mean(follow);
  const loit = []; for (let i = 0; i < n; i++) if (O.mode[i] === MODE.LOITER) loit.push(O.Pel[i]);
  const pLoiter = mean(loit);
  const endurance = enduranceMin(p.bankWh * XFER + p.battWh, pMean, { heated: true });
  const flyUsableWh = p.battWh * p.coldFactor * (1 - p.reserve);
  // standstill and actions (full run only)
  const crashed = has('snowStrike'), fs = has('failsafe') || has('geofence'), anywhere = has('landAnywhere');
  const slide = core.sum.slide;
  let setup = NaN, ops = NaN, endWait = NaN, restDist = NaN, walk = NaN;
  if (fullRun && noFly) { // no-fly run: everything happens at the top before the rider leaves; no footage
    const s0 = core.rider(0);
    restDist = slide.restPos ? Math.hypot(slide.restPos[0] - s0.pos[0], slide.restPos[1] - s0.pos[1]) : NaN;
    walk = crashed || !Number.isFinite(restDist) || restDist > 12 ? 30 : Math.max(0, restDist - 1) * WALK_S_PER_M;
    endWait = (slide.restT ?? (n - 1) * dt) - DRAW_S;
    setup = DRAW_S + endWait + walk + STOW_S; ops = 2 + (crashed ? 1 : 0);
  } else if (fullRun) {
    const tStop = sk.stops.length ? sk.stops[sk.stops.length - 1].t0 : NaN;
    if (slide.restT != null) {
      const s = core.rider(slide.restT);
      restDist = Math.hypot(slide.restPos[0] - s.pos[0], slide.restPos[1] - s.pos[1]);
      endWait = Math.max(0, slide.restT - tStop);
      walk = Math.max(0, restDist - 1.0) * WALK_S_PER_M;
    }
    const recovery = crashed || fs || anywhere || slide.restT == null || restDist > 12;
    if (recovery) { // walk/side-step to wherever it came down (ASSUMED 30 s) instead of the planned pick-up
      endWait = Number.isFinite(endWait) ? endWait : 0; walk = 30;
    }
    setup = (pre ?? DRAW_S) + endWait + walk + STOW_S;
    ops = 2 + (crashed ? 1 : 0) + (fs ? 1 : 0) + (anywhere && !crashed ? 1 : 0) + (slide.restT == null && !crashed ? 1 : 0);
  }
  // catch-up after each push-off: time from the push-off until range < 10 m (rider speed > 6 m/s)
  const catchUp = [];
  if (fullRun) for (const r of sk.rides) { let tc = NaN; for (let i = Math.round(r.t0 / dt); i < Math.min(n, Math.round(r.t1 / dt)); i++) if (O.range[i] < 10) { tc = i * dt - r.t0; break; } catchUp.push(tc); }
  return {
    noFly, avail: noFly ? 0 : avail, pxMed: med(pxs), jitter, jitterPct, attRateRms, azRange, keMax, headMin, aglMin, gsMax, lensLossPct: nSki ? (100 * nLens) / nSki : NaN,
    rangeMax: core.sum.rangeMax, Ewh, Trun, pMean, pFollow, pLoiter, endurance, runsPerCharge: flyUsableWh / Math.max(1e-6, Ewh),
    rechargeC: Ewh / (p.battWh * (LIFT_MIN / 60)), setup, ops, endWait, restDist, walk, tdKE: slide.tdKE, tdV: slide.tdV, slideDist: slide.dist,
    landMinRider: slide.minRider, crashed, failsafe: fs, catchUp, tReady: pre, keCapT: core.sum.keCapT, propHeadMin: core.sum.throwInfo.propHeadMin, throwMinAGL: core.sum.throwInfo.minAGL,
    goArounds: ev.filter((e) => e.type === 'goAround').length, stall: ev.some((e) => e.type === 'stall'),
  };
}

